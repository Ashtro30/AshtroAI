# ---------------------------------------------------------------- python_eval
def test_python_eval_prints_and_echoes_expression(reg, ctx):
    assert reg.execute("python_eval", {"code": "print(2+2)"}, ctx).output == "4"
    assert reg.execute("python_eval", {"code": "x = 6\nx * 7"}, ctx).output == "42"


def test_python_eval_numpy_pandas_and_csv(reg, ctx):
    code = (
        "import numpy as np\nimport pandas as pd\n"
        "df = load_csv('quarterly_sales.csv')\n"
        "print(df.groupby('region').revenue_usd.sum().idxmax())\n"
        "print(float(np.mean([1,2,3])))"
    )
    r = reg.execute("python_eval", {"code": code}, ctx)
    assert r.ok, r.output
    assert r.output.splitlines() == ["East", "2.0"]


def test_python_eval_runtime_error_is_reported_with_hint(reg, ctx):
    r = reg.execute("python_eval", {"code": "print(1/0)"}, ctx)
    assert not r.ok and "ZeroDivisionError" in r.output and "Hint" in r.output
    r = reg.execute("python_eval", {"code": "np.mean([1])"}, ctx)
    assert not r.ok and "import numpy" in r.output


def test_python_eval_syntax_error(reg, ctx):
    r = reg.execute("python_eval", {"code": "def f(:\n  pass"}, ctx)
    assert not r.ok and "SyntaxError" in r.output


@pytest.mark.parametrize(
    "code",
    [
        "import os\nprint(os.listdir('.'))",
        "import subprocess",
        "from os import system",
        "open('/etc/passwd').read()",
        "print(().__class__.__bases__)",
        "eval('1+1')",
        "getattr(int, 'real')",
        "import statistics\nstatistics.sys.modules",
        "import pandas as pd\npd.read_csv('/etc/passwd')",
        "print('{0.__class__}'.format(1))",
    ],
)
def test_python_eval_blocks_dangerous_code(reg, ctx, code):
    r = reg.execute("python_eval", {"code": code}, ctx)
    assert not r.ok, f"sandbox let this through: {code!r} -> {r.output}"


def test_python_eval_load_csv_cannot_escape_data_dir(reg, ctx):
    r = reg.execute("python_eval", {"code": "print(load_csv('../../etc/passwd'))"}, ctx)
    assert not r.ok


def test_python_eval_timeout(reg, ctx):
    r = reg.execute("python_eval", {"code": "while True:\n    pass"}, ctx.__class__(ctx.settings.with_overrides(python_timeout=2), ctx.memory, "t"))
    assert not r.ok and "time limit" in r.output


def test_python_eval_does_not_leak_environment(reg, ctx, monkeypatch):
    monkeypatch.setenv("SECRET_API_KEY", "hunter2")
    r = reg.execute("python_eval", {"code": "print('ok')"}, ctx)
    assert r.ok and "hunter2" not in r.output


# ------------------------------------------------------------ generate_report
def test_generate_report_writes_markdown(reg, ctx):
    r = reg.execute("generate_report", {"filename": "summary", "title": "My Summary", "content": "- a\n- b"}, ctx)
    assert r.ok and "outputs/summary.md" in r.output
    text = (ctx.settings.outputs_dir / "summary.md").read_text()
    assert text.startswith("# My Summary") and "- a" in text and "Generated by Ashtro-AI" in text


def test_generate_report_blocks_traversal_and_bad_ext(reg, ctx):
    r = reg.execute("generate_report", {"filename": "../../evil.md", "content": "x"}, ctx)
    assert r.ok and (ctx.settings.outputs_dir / "evil.md").exists()  # directory parts are stripped
    assert not (ctx.settings.outputs_dir.parent.parent / "evil.md").exists()
    bad = reg.execute("generate_report", {"filename": "run.exe", "content": "x"}, ctx)
    assert not bad.ok and "not allowed" in bad.output


def test_generate_report_append_and_empty(reg, ctx):
    reg.execute("generate_report", {"filename": "log.md", "content": "# Log\none"}, ctx)
    reg.execute("generate_report", {"filename": "log.md", "content": "two", "mode": "append"}, ctx)
    text = (ctx.settings.outputs_dir / "log.md").read_text()
    assert "one" in text and "two" in text
    assert not reg.execute("generate_report", {"filename": "x.md", "content": " "}, ctx).ok


# --------------------------------------------------------------- task_manager
def test_task_manager_lifecycle(reg, ctx):
    r = reg.execute("task_manager", {"action": "plan", "goal": "Ship", "steps": ["a", "b", "c"]}, ctx)
    assert r.ok and "Created 3 tasks" in r.output
    r = reg.execute("task_manager", {"action": "update", "task_id": 1, "status": "in_progress"}, ctx)
    assert r.ok and "in_progress" in r.output
    r = reg.execute("task_manager", {"action": "update", "task_id": "2", "status": "done"}, ctx)  # str id coerced
    assert r.ok and "1/3 done" in r.output
    assert "Next task: 1." in reg.execute("task_manager", {"action": "next"}, ctx).output
    reg.execute("task_manager", {"action": "add", "title": "d", "priority": "high"}, ctx)
    board = load_tasks(ctx.settings, ctx.session_id)
    assert len(board["tasks"]) == 4
    assert update_task_status(ctx.settings, ctx.session_id, 3, "blocked")
    assert not update_task_status(ctx.settings, ctx.session_id, 99, "done")


def test_task_manager_errors_are_descriptive(reg, ctx):
    assert "needs 'steps'" in reg.execute("task_manager", {"action": "plan", "goal": "x"}, ctx).output
    r = reg.execute("task_manager", {"action": "update", "task_id": 9, "status": "done"}, ctx)
    assert not r.ok and "does not exist" in r.output
    r = reg.execute("task_manager", {"action": "explode"}, ctx)
    assert not r.ok and "one of" in r.output


def test_task_manager_steps_as_newline_text(reg, ctx):
    r = reg.execute("task_manager", {"action": "plan", "goal": "g", "steps": "1. first\n2. second\n- third"}, ctx)
    assert r.ok and "Created 3 tasks" in r.output and "first" in r.output
