"""Unit tests for the four tools and the registry's error handling."""

from __future__ import annotations

import pytest

from agent.tools import ToolRegistry, load_tasks, update_task_status


@pytest.fixture()
def reg() -> ToolRegistry:
    return ToolRegistry()


# ----------------------------------------------------------- registry basics
def test_unknown_tool_lists_available(reg, ctx):
    r = reg.execute("nope", {}, ctx)
    assert not r.ok and "Available tools" in r.output and "python_eval" in r.output


def test_missing_and_unknown_args(reg, ctx):
    assert "missing required argument 'query'" in reg.execute("search_documents", {}, ctx).output
    r = reg.execute("search_documents", {"query": "x", "bogus": 1}, ctx)
    assert not r.ok and "unexpected argument" in r.output


def test_describe_mentions_all_tools(reg):
    doc = reg.describe()
    for name in ("search_documents", "python_eval", "generate_report", "task_manager"):
        assert name in doc


